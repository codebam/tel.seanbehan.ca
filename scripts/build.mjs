#!/usr/bin/env node
// Compiles every .tel file in this project with the Tel toolchain.
//
//   node scripts/build.mjs               # check + build Worker and browser island
//   node scripts/build.mjs --check-only  # static check only
//
// Compiler resolution order:
//   1. $TEL_BIN (path to bin/tel.mjs) or $TEL_REPO
//   2. ../tel-token-efficient-lang/bin/tel.mjs (sibling checkout)
//   3. node_modules/tel-lang/bin/tel.mjs
//   4. the published package: npx --yes @codebam/tel

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(root, "src");
const distDir = path.join(root, "dist");
const assetsDir = path.join(root, "public", "assets");
const checkOnly = process.argv.includes("--check-only");

function findLocalCompiler() {
  const candidates = [
    process.env.TEL_BIN,
    process.env.TEL_REPO && path.join(process.env.TEL_REPO, "bin", "tel.mjs"),
    path.join(root, "..", "tel-token-efficient-lang", "bin", "tel.mjs"),
    path.join(root, "node_modules", "tel-lang", "bin", "tel.mjs"),
  ].filter(Boolean);
  return candidates.find((p) => fs.existsSync(p));
}

const localCompiler = findLocalCompiler();
const npxCommand = process.platform === "win32" ? "npx.cmd" : "npx";
const compilerCommand = localCompiler ? process.execPath : npxCommand;
const compilerArgs = localCompiler ? [localCompiler] : ["--yes", "@codebam/tel"];
if (!localCompiler) console.log("build: no local Tel checkout found; using npx --yes @codebam/tel");

function tel(args) {
  const result = spawnSync(compilerCommand, [...compilerArgs, ...args], { cwd: root, stdio: "inherit" });
  if (result.error) {
    console.error(`build: failed to run Tel (${compilerCommand} ${compilerArgs.join(" ")}): ${result.error.message}`);
    console.error("build: ensure Node >= 20 is installed and npm can reach the registry, or set TEL_BIN=/path/to/bin/tel.mjs");
    process.exit(1);
  }
  if (result.status !== 0) process.exit(result.status ?? 1);
}

function telFiles(dir) {
  const out = [];
  for (const rel of fs.readdirSync(dir, { recursive: true })) {
    if (typeof rel === "string" && rel.endsWith(".tel")) out.push(path.join(dir, rel));
  }
  return out.sort();
}

function rm(file) {
  fs.rmSync(file, { recursive: true, force: true });
}

function size(file) {
  try {
    return `${(fs.statSync(file).size / 1024).toFixed(1)} KB`;
  } catch {
    return "missing";
  }
}

function directorySize(dir) {
  let total = 0;
  for (const rel of fs.readdirSync(dir, { recursive: true })) {
    const full = path.join(dir, rel);
    if (fs.statSync(full).isFile()) total += fs.statSync(full).size;
  }
  return `${(total / 1024).toFixed(1)} KB`;
}

const sources = telFiles(srcDir);
if (fs.existsSync(path.join(root, "main.tel"))) sources.push(path.join(root, "main.tel"));
console.log(`build: checking ${sources.length} Tel source files`);
tel(["check", ...sources]);

if (checkOnly) {
  console.log("build: check passed");
  process.exit(0);
}

rm(distDir);
fs.mkdirSync(distDir, { recursive: true });
fs.mkdirSync(assetsDir, { recursive: true });
for (const generated of ["app.mjs", "content.mjs", "highlight.mjs", "estimate.mjs"]) {
  rm(path.join(assetsDir, generated));
}

console.log("build: compiling Worker (--target web)");
tel(["build", path.join(srcDir, "worker.tel"), "--target", "web", "--outdir", distDir, "--quiet"]);

console.log("build: compiling browser island (--target web)");
tel(["build", path.join(srcDir, "app.tel"), "--target", "web", "--outdir", assetsDir, "--quiet"]);

// Tel's compiled output keeps relative ESM imports; ship the tiny globals shim
// next to the Worker bundle and generate the Cloudflare entry point.
fs.copyFileSync(path.join(srcDir, "worker-globals.mjs"), path.join(distDir, "worker-globals.mjs"));
fs.writeFileSync(
  path.join(distDir, "worker-entry.mjs"),
  `// Generated by scripts/build.mjs — do not edit.\n` +
    `import * as tel from "./worker.mjs";\n\n` +
    `export default {\n` +
    `  fetch(request, env, ctx) {\n` +
    `    return tel.fetch(request, env, ctx);\n` +
    `  },\n` +
    `};\n`,
);

console.log(`build: dist ${directorySize(distDir)} -> ${path.relative(root, path.join(distDir, "worker-entry.mjs"))}`);
console.log(`build: browser ${directorySize(assetsDir)} -> ${path.relative(root, path.join(assetsDir, "app.mjs"))} (${size(path.join(assetsDir, "app.mjs"))} entry)`);
console.log("build: ok");
